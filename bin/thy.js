#!/usr/bin/env node
'use strict';

/**
 * thy - ThyScript multi-command CLI
 * Commands: compile, check, use, new, run, repl, test, build, serve
 */

const path      = require('path');
const fs        = require('fs');
const { execSync, spawn } = require('child_process');

// ─── Bootstrap optional deps ─────────────────────────────────────────────────
let chalk, ora, commander;
try { chalk = require('chalk'); }
catch {
  chalk = new Proxy({}, {
    get: (_, k) => k === 'bold' || k === 'bgGreen' || k === 'bgRed'
      ? new Proxy({}, { get: (_, k2) => (s) => s })
      : (s) => s,
  });
}
try { ora = require('ora'); }
catch {
  ora = (text) => ({
    text, start() { process.stdout.write(`  ⏳  ${this.text}...\n`); return this; },
    succeed(m) { process.stdout.write(`  ✅  ${m || this.text}\n`); return this; },
    fail(m)    { process.stdout.write(`  ❌  ${m || this.text}\n`); return this; },
    info(m)    { process.stdout.write(`  ℹ️   ${m || this.text}\n`); return this; },
    stop()     { return this; },
  });
}
try { commander = require('commander'); }
catch {
  console.error('commander not found. Run: npm install commander');
  process.exit(1);
}

const { Command } = commander;

// ─── Constants ────────────────────────────────────────────────────────────────
const THYSCRIPT_ROOT = path.resolve(__dirname, '..');
const PKG_PATH       = path.join(THYSCRIPT_ROOT, 'package.json');
let   VERSION        = '1.0.0';
try   { VERSION = require(PKG_PATH).version || VERSION; } catch {}

// ─── Helpers ──────────────────────────────────────────────────────────────────
const log  = (...a) => console.log(...a);
const info = (msg)  => log(chalk.cyan(`  ℹ️   ${msg}`));
const ok   = (msg)  => log(chalk.green(`  ✔   ${msg}`));
const warn = (msg)  => log(chalk.yellow(`  ⚠️   ${msg}`));
const fail = (msg)  => log(chalk.red(`  ✖   ${msg}`));
const sep  = ()     => log(chalk.cyan('  ' + '─'.repeat(68)));

function header(title) {
  sep();
  log(chalk.bold.cyan(`  ${title}`));
  sep();
}

function ensureThyFile(f) {
  const abs = path.resolve(process.cwd(), f);
  if (!fs.existsSync(abs)) { fail(`File not found: ${abs}`); process.exit(1); }
  return abs;
}

function tryRequire(rel) {
  try { return require(path.join(THYSCRIPT_ROOT, rel)); } catch { return null; }
}

function npmInstall(pkg, cwd) {
  const spinner = ora(`Installing ${pkg}...`).start();
  try {
    execSync(`npm install ${pkg}`, { cwd, stdio: 'pipe' });
    spinner.succeed(chalk.green(`Installed ${pkg}`));
    return true;
  } catch (err) {
    spinner.fail(chalk.red(`Failed to install ${pkg}: ${err.message}`));
    return false;
  }
}

// ─── Mini banner (no full ASCII for subcommand output) ────────────────────────
function miniBanner() {
  log('');
  log(chalk.bold.cyan('  ⚡ ThyScript v' + VERSION));
  log(chalk.gray('  High-Performance Language Built on Node.js'));
  log('');
}

// ─── Scaffold templates ───────────────────────────────────────────────────────
function getMainTemplate(name) {
  return `// ${name} - ThyScript Application
// Generated by ThyScript CLI v${VERSION}

print("Hello from ${name}!")
let x: int = 42
print("The answer is: " + x)

// Define a simple reusable function
func greet(person):
  return "Hello, " + person + "!"
end()
print(greet("ThyScript"))
`;
}

function getPackageJsonTemplate(name) {
  return JSON.stringify({
    name: name.toLowerCase().replace(/\s+/g, '-'),
    version: '0.1.0',
    description: `ThyScript project: ${name}`,
    main: 'src/main.thy',
    scripts: {
      start: `thy run src/main.thy`,
      build: `thy build src/main.thy`,
      test:  `thy test`,
    },
    keywords: ['thyscript'],
    license: 'MIT',
    dependencies: {},
    devDependencies: {},
    thyscript: {
      version: VERSION,
      entry: 'src/main.thy',
      outDir: 'dist',
    },
  }, null, 2);
}

function getReadmeTemplate(name) {
  return `# ${name}

A ThyScript project.

## Getting Started

\`\`\`bash
thy run src/main.thy
\`\`\`

## Build

\`\`\`bash
thy build src/main.thy
\`\`\`

## Test

\`\`\`bash
thy test
\`\`\`
`;
}

function getGitignoreTemplate() {
  return `node_modules/
dist/
*.thy.js
*.thy.map
.env
.thy-cache/
`;
}

// ─── Program definition ───────────────────────────────────────────────────────
const program = new Command();

program
  .name('thy')
  .description('ThyScript - High-performance language CLI')
  .version(VERSION, '-v, --version', 'Show ThyScript version');

// ╔══════════════════════════════════════╗
// ║  thy compile <filename>              ║
// ╚══════════════════════════════════════╝
program
  .command('compile <filename>')
  .description('Compile a .thy file to Node.js JavaScript')
  .option('-o, --out <outfile>', 'Output filename (default: <filename>.js)')
  .option('--minify', 'Minify output')
  .option('--sourcemap', 'Generate source map')
  .action(async (filename, opts) => {
    miniBanner();
    header('COMPILE');

    const abs     = ensureThyFile(filename);
    const outFile = opts.out || abs + '.js';
    const source  = fs.readFileSync(abs, 'utf8');
    const display = path.basename(abs);

    const spinner = ora(chalk.cyan(`Compiling ${display}...`)).start();

    const ThyMod = tryRequire('src/index.js');
    if (!ThyMod || typeof ThyMod.compile !== 'function') {
      spinner.fail(chalk.red('ThyScript compiler not found. Run: thy check'));
      process.exit(1);
    }

    try {
      const t0    = Date.now();
      let   js    = ThyMod.compile(source, abs);

      if (opts.minify) {
        // Basic whitespace minification (real minifier hooked via UglifyJS if available)
        try {
          const uglify = require('uglify-js');
          const res    = uglify.minify(js);
          if (!res.error) js = res.code;
        } catch {
          warn('uglify-js not available — skipping minification. Install with: npm install uglify-js');
        }
      }

      fs.writeFileSync(outFile, js, 'utf8');

      if (opts.sourcemap) {
        // Stub source map
        const map = JSON.stringify({
          version: 3, file: path.basename(outFile),
          sources: [display], mappings: '',
        });
        fs.writeFileSync(outFile + '.map', map, 'utf8');
        ok(`Source map: ${outFile}.map`);
      }

      const ms = Date.now() - t0;
      spinner.succeed(chalk.green(`Compiled in ${ms}ms → ${outFile}`));
    } catch (err) {
      spinner.fail(chalk.red(`Compile error: ${err.message}`));
      if (err.line) fail(`  at line ${err.line}, col ${err.column}`);
      if (err.suggestion) warn(`  Fix: ${err.suggestion}`);
      process.exit(1);
    }
  });

// ╔══════════════════════════════════════╗
// ║  thy check                           ║
// ╚══════════════════════════════════════╝
program
  .command('check')
  .description('Check npm dependencies and install missing ones')
  .option('--fix', 'Automatically install missing packages')
  .action((opts) => {
    miniBanner();
    header('DEPENDENCY CHECK');

    const required = [
      'chalk', 'ora', 'commander', 'chokidar', 'express',
      'ws', 'better-sqlite3', 'jsonwebtoken', 'bcryptjs',
    ];
    const optional = [
      'uglify-js', 'terser', 'readline-sync',
    ];

    const cwd = process.cwd();
    const hasPkg = fs.existsSync(path.join(cwd, 'package.json'));
    if (!hasPkg) {
      warn('No package.json found in current directory.');
      if (opts.fix) {
        log(chalk.cyan('  Running npm init -y...'));
        execSync('npm init -y', { cwd, stdio: 'inherit' });
      }
    }

    let missing = [];
    log(chalk.bold.white('  Required packages:'));
    for (const pkg of required) {
      try {
        require.resolve(pkg);
        log(chalk.green(`    ✔  ${pkg}`));
      } catch {
        log(chalk.red(`    ✖  ${pkg} (missing)`));
        missing.push(pkg);
      }
    }

    log('');
    log(chalk.bold.white('  Optional packages:'));
    for (const pkg of optional) {
      try {
        require.resolve(pkg);
        log(chalk.green(`    ✔  ${pkg}`));
      } catch {
        log(chalk.gray(`    ○  ${pkg} (not installed)`));
      }
    }

    log('');
    if (missing.length === 0) {
      ok('All required dependencies are present!');
    } else {
      warn(`${missing.length} package(s) missing: ${missing.join(', ')}`);
      if (opts.fix) {
        log('');
        log(chalk.cyan('  Installing missing packages...'));
        for (const pkg of missing) npmInstall(pkg, cwd);
      } else {
        log(chalk.yellow('  Run: thy check --fix   to auto-install'));
      }
    }
  });

// ╔══════════════════════════════════════╗
// ║  thy use <package>                   ║
// ╚══════════════════════════════════════╝
program
  .command('use <package>')
  .description('Install an npm package and register it in the project')
  .option('-D, --dev', 'Save as devDependency')
  .action((pkg, opts) => {
    miniBanner();
    header(`ADDING PACKAGE: ${pkg}`);

    const cwd     = process.cwd();
    const flag    = opts.dev ? '--save-dev' : '--save';
    const spinner = ora(`Installing ${pkg}...`).start();

    try {
      execSync(`npm install ${pkg} ${flag}`, { cwd, stdio: 'pipe' });
      spinner.succeed(chalk.green(`Package '${pkg}' installed and saved.`));

      // Update thyscript block in package.json if present
      const pkgPath = path.join(cwd, 'package.json');
      if (fs.existsSync(pkgPath)) {
        const pkgJson = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
        pkgJson.thyscript = pkgJson.thyscript || {};
        pkgJson.thyscript.uses = pkgJson.thyscript.uses || [];
        if (!pkgJson.thyscript.uses.includes(pkg)) {
          pkgJson.thyscript.uses.push(pkg);
          fs.writeFileSync(pkgPath, JSON.stringify(pkgJson, null, 2), 'utf8');
          ok(`Registered '${pkg}' in package.json [thyscript.uses]`);
        }
      }
    } catch (err) {
      spinner.fail(chalk.red(`Failed to install '${pkg}': ${err.message}`));
      process.exit(1);
    }
  });

// ╔══════════════════════════════════════╗
// ║  thy install <pkg1> [pkg2...]        ║
// ╚══════════════════════════════════════╝
program
  .command('install')
  .description('Install any npm package(s) for immediate use with `import "<pkg>"`')
  .argument('[pkgs...]', 'One or more npm package names')
  .option('-D, --dev', 'Save as devDependency')
  .action((pkgs, opts) => {
    miniBanner();
    header('INSTALL NPM PACKAGE  (use it with  import "<pkg>")');
    doInstallPkgs(pkgs, opts);
  });

function doInstallPkgs(pkgs, opts) {
  if (!pkgs || pkgs.length === 0) {
    warn('Usage: thy install <package> [package...]');
    warn('Examples:');
    warn('  thy install axios lodash dayjs');
    warn('  thy install express');
    process.exit(0);
  }

  const cwd = process.cwd();
  const flag = opts.dev ? '--save-dev' : '--save';

  for (const pkg of pkgs) {
    if (npmInstall(pkg + ' ' + flag, cwd)) {
      // Register in project's package.json under thyscript.uses
      const pkgPath = path.join(cwd, 'package.json');
      if (fs.existsSync(pkgPath)) {
        try {
          const pkgJson = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
          pkgJson.thyscript = pkgJson.thyscript || {};
          pkgJson.thyscript.uses = pkgJson.thyscript.uses || [];
          if (!pkgJson.thyscript.uses.includes(pkg)) {
            pkgJson.thyscript.uses.push(pkg);
            fs.writeFileSync(pkgPath, JSON.stringify(pkgJson, null, 2), 'utf8');
            ok(`Registered '${pkg}' → import "${pkg}"`);
          }
        } catch (_) {}
      } else {
        ok(`Installed '${pkg}'. Add import "${pkg}" to your .thy code.`);
      }
    }
  }

  log('');
  ok('Done. Use it in ThyScript like:');
  log(chalk.cyan('    import "' + pkgs[0] + '"'));
  if (pkgs.length > 1) log(chalk.gray('    // ...and any of the other installed packages'));
  log('');
}

