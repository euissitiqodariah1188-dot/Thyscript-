program
  .command('new <project-name>')
  .description('Scaffold a new ThyScript project')
  .option('--no-git', 'Skip git initialization')
  .option('--no-install', 'Skip npm install')
  .action((name, opts) => {
    miniBanner();
    header(`NEW PROJECT: ${name}`);

    const projectDir = path.resolve(process.cwd(), name);
    if (fs.existsSync(projectDir)) {
      fail(`Directory already exists: ${projectDir}`);
      process.exit(1);
    }

    const spinner = ora('Scaffolding project...').start();

    try {
      // Create directory structure
      const dirs = [
        projectDir,
        path.join(projectDir, 'src'),
        path.join(projectDir, 'tests'),
        path.join(projectDir, 'dist'),
        path.join(projectDir, 'docs'),
      ];
      dirs.forEach(d => fs.mkdirSync(d, { recursive: true }));

      // Write files
      fs.writeFileSync(path.join(projectDir, 'src', 'main.thy'),
        getMainTemplate(name), 'utf8');
      fs.writeFileSync(path.join(projectDir, 'package.json'),
        getPackageJsonTemplate(name), 'utf8');
      fs.writeFileSync(path.join(projectDir, 'README.md'),
        getReadmeTemplate(name), 'utf8');
      fs.writeFileSync(path.join(projectDir, '.gitignore'),
        getGitignoreTemplate(), 'utf8');
      fs.writeFileSync(path.join(projectDir, 'tests', 'main.test.thy'),
        `// Tests for ${name}\nprint("Test suite for ${name} passed!")\n`, 'utf8');

      spinner.succeed(chalk.green(`Project scaffolded: ${projectDir}`));

      // Git init
      if (opts.git !== false) {
        try {
          execSync('git init', { cwd: projectDir, stdio: 'pipe' });
          ok('Initialized git repository');
        } catch { warn('git not available — skipping'); }
      }

      // npm install
      if (opts.install !== false) {
        const installSpinner = ora('Installing ThyScript dependencies...').start();
        try {
          execSync(`npm install thyscript chalk ora commander`, {
            cwd: projectDir, stdio: 'pipe',
          });
          installSpinner.succeed('Dependencies installed');
        } catch {
          installSpinner.fail('npm install failed — run manually inside the project');
        }
      }

      log('');
      ok(`Done! Your ThyScript project is ready.`);
      log('');
      log(chalk.cyan(`  Next steps:`));
      log(chalk.white(`    cd ${name}`));
      log(chalk.white(`    thy run src/main.thy`));
      log('');
    } catch (err) {
      spinner.fail(chalk.red(`Failed: ${err.message}`));
      process.exit(1);
    }
  });

