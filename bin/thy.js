program
  .command('serve <filename>')
  .description('Run a .thy file as a real live HTTP web server (accessible anywhere)')
  .option('-p, --port <port>', 'Port to listen on', '3000')
  .option('--host <host>', 'Host to bind to', '0.0.0.0')
  .option('--public', 'Also expose the server to the PUBLIC internet via a tunnel URL')
  .option('--subdomain <sub>', 'Preferred public subdomain (with --public)')
  .option('--watch', 'Restart on file change')
  .action(async (filename, opts) => {
    miniBanner();
    header('THY SERVER');

    const abs    = ensureThyFile(filename);
    const port   = parseInt(opts.port, 10) || 3000;
    const host   = opts.host || '0.0.0.0';
    process.env.PORT = String(port);
    process.env.HOST = host;

    info(`Starting server: ${path.basename(abs)}`);

    const os = require('os');
    const ifaces = os.networkInterfaces();
    const netAddrs = [];
    for (const name of Object.keys(ifaces)) {
      for (const iface of ifaces[name] || []) {
        if (iface.family === 'IPv4' && !iface.internal) {
          netAddrs.push({ name, address: iface.address });
        }
      }
    }

    async function startServer() {
      try {
        const ThyMod = tryRequire('src/index.js');
        if (!ThyMod) {
          fail('ThyScript core not found.');
          process.exit(1);
        }

        const source = fs.readFileSync(abs, 'utf8');
        await ThyMod.runSource(source, abs);

        ok(`Server successfully running on http://${host === '0.0.0.0' ? 'localhost' : host}:${port}`);
        if (netAddrs.length > 0) {
          log('');
          log(chalk.bold.white('  🌐 Access from any device on your local network (WiFi/LAN):'));
          for (const net of netAddrs) {
            log(chalk.cyan(`     ▶ http://${net.address}:${port}`) + chalk.gray(` (${net.name})`));
          }
        }
        log('');
      } catch (err) {
        if (err.code === 'EADDRINUSE') {
          fail(`Port ${port} is already in use.`);
          warn(`Try: thy serve ${filename} --port ${port + 1}`);
        } else {
          fail(`Server error: ${err.message}`);
        }
        process.exit(1);
      }
    }

    await startServer();

    if (opts.public) {
      const TunnelEngine = tryRequire('src/server/TunnelEngine.js');
      if (TunnelEngine) {
        const engine = new TunnelEngine({
          port,
          subdomain: opts.subdomain || null,
        });
        if (!engine.available) {
          warn('localtunnel is not installed. Run: npm install localtunnel  (then re-run)');
        } else {
          log('');
          log(chalk.bold.white('  🌍  Exposing server to the PUBLIC internet...'));
          try {
            const result = await engine.start();
            log('');
            log(chalk.bold.green('  ✅  PUBLIC URL (accessible from anywhere!):'));
            log(chalk.cyan(`     ▶  `) + chalk.bold.underline.cyan(result.publicUrl));
            log('');
            process.on('SIGINT', async () => { await engine.stop(); process.exit(0); });
          } catch (err) {
            warn(`Public tunnel failed (server still running locally): ${err.message}`);
            warn('Re-run with: thy serve ' + filename + ' --port ' + port + ' --public');
          }
        }
      } else {
        warn('TunnelEngine not found — public mode unavailable.');
      }
    }

    if (opts.watch) {
      let chokidar;
      try { chokidar = require('chokidar'); } catch {
        warn('chokidar not installed — watch disabled');
        return;
      }
      log(chalk.cyan('  👁  Watching for file changes...'));
      chokidar.watch(abs).on('change', async () => {
        warn('File changed. Restarting server...');
        await startServer();
      });
    }
  });

