program
  .command('tunnel')
  .description('Expose a local port to the PUBLIC internet with a real URL (https://<sub>.loca.lt)')
  .option('-p, --port <port>', 'Local port to expose', '3000')
  .option('-s, --subdomain <sub>', 'Preferred public subdomain (e.g. my-app)')
  .option('-h, --host <host>', 'localtunnel server host (default loca.lt)')
  .option('--no-check', 'Skip pre-flight connectivity check')
  .action(async (opts) => {
    miniBanner();
    header('EXTERNAL PUBLIC TUNNEL  (ACCESS FROM ANYWHERE)');

    const port = parseInt(opts.port, 10) || 3000;
    if (!(port > 0 && port <= 65535)) {
      fail(`Invalid port: ${port}`);
      process.exit(1);
    }

    const TunnelEngine = tryRequire('src/server/TunnelEngine.js');
    if (!TunnelEngine) {
      fail('TunnelEngine module not found.');
      process.exit(1);
    }

    const engine = new TunnelEngine({
      port,
      subdomain: opts.subdomain || null,
      host: opts.host || null,
    });

    if (!engine.available) {
      warn('localtunnel is not installed. Installing it now...');
      const target = path.join(THYSCRIPT_ROOT, 'package.json');
      if (!npmInstall('localtunnel@^2.0.2', path.dirname(target))) {
        fail('Failed to install localtunnel. Run: npm install localtunnel');
        process.exit(1);
      }
      delete require.cache[require.resolve('localtunnel')];
    }

    info(`Exposing localhost:${port} to the public internet...`);

    if (opts.check !== false) {
      log(chalk.gray('  ⏳  Checking localtunnel server connectivity...'));
      const okNet = await engine.pingHost(5000);
      if (!okNet) {
        warn('Pre-flight check could not reach localtunnel (HEAD blocked by network).');
        warn('Attempting to open the tunnel anyway...');
      } else {
        ok('Connectivity confirmed. Opening tunnel...');
      }
    }

    try {
      const result = await engine.start();
      log('');
      log(chalk.bold.green('  ✅  PUBLIC TUNNEL IS LIVE!'));
      log('');
      log(chalk.bold.white('  🌍  Access your computer from anywhere on the internet:'));
      log('');
      log(chalk.cyan('       ▶  ') + chalk.bold.underline.cyan(result.publicUrl));
      log('');
      log(chalk.gray('  ─────────────────────────────────────────────────────────'));
      log(chalk.gray('  This URL is reachable from any device/network worldwide.'));
      log(chalk.gray('  The tunnel proxies to http://127.0.0.1:' + port +
        ' on this machine.'));
      log(chalk.gray('  Keep this terminal open — closing it stops the tunnel.'));
      log('');
      log(chalk.gray('  Press Ctrl+C to stop the public tunnel.'));
      log('');
      process.on('SIGINT', async () => {
        await engine.stop();
        process.exit(0);
      });
      // Keep process alive while the tunnel runs
      process.stdin.resume();
    } catch (err) {
      fail(`Failed to open tunnel: ${err.message}`);
      log('');
      warn('Make sure you have a server already running on port ' + port +
        ' (e.g. `thy serve app.thy --port ' + port + '`).');
      warn('If the subdomain is taken, run without -s to get a random URL.');
      process.exit(1);
    }
  });

