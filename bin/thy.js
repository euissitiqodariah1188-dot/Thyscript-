// ╔══════════════════════════════════════╗
// ║  thy repl                            ║
// ╚══════════════════════════════════════╝
program
  .command('repl')
  .description('Start the interactive ThyScript REPL')
  .action(async () => {
    miniBanner();
    header('THYSCRIPT REPL  (type .exit to quit, .help for commands)');

    const readline = require('readline');
    const rl = readline.createInterface({
      input:  process.stdin,
      output: process.stdout,
      prompt: chalk.cyan('thy> '),
    });

    const ThyMod  = tryRequire('src/index.js');
    const history = [];
    let   scope   = {};
    let   multi   = '';       // multi-line buffer
    let   depth   = 0;        // brace depth

    log(chalk.gray('  ThyScript Interactive REPL'));
    log(chalk.gray('  .help  .clear  .history  .exit'));
    log('');
    rl.prompt();

    rl.on('line', async (line) => {
      const trimmed = line.trim();

      // REPL commands
      if (trimmed === '.exit') { log(chalk.cyan('  Goodbye!')); rl.close(); process.exit(0); }
      if (trimmed === '.clear') { scope = {}; multi = ''; depth = 0; ok('Scope cleared.'); rl.prompt(); return; }
      if (trimmed === '.help') {
        log(chalk.yellow('  .exit     — quit REPL'));
        log(chalk.yellow('  .clear    — clear scope'));
        log(chalk.yellow('  .history  — show history'));
        log(chalk.yellow('  .scope    — show current variables'));
        rl.prompt(); return;
      }
      if (trimmed === '.history') {
        history.forEach((h, i) => log(chalk.gray(`  ${i + 1}: ${h}`)));
        rl.prompt(); return;
      }
      if (trimmed === '.scope') {
        log(JSON.stringify(scope, null, 2));
        rl.prompt(); return;
      }

      if (!trimmed) { rl.prompt(); return; }

      // Multi-line detection: count braces
      for (const ch of line) {
        if (ch === '{') depth++;
        else if (ch === '}') depth--;
      }
      multi += line + '\n';

      if (depth > 0) {
        rl.setPrompt(chalk.cyan('... '));
        rl.prompt();
        return;
      }

      // Execute
      const code = multi.trim();
      multi = ''; depth = 0;
      rl.setPrompt(chalk.cyan('thy> '));

      if (code) {
        history.push(code);
        try {
          if (ThyMod && typeof ThyMod.compile === 'function') {
            const js  = ThyMod.compile(code, '<repl>');
            const fn  = new Function('__scope__', `with(__scope__){ ${js} }`);
            const res = await fn(scope);
            if (res !== undefined) log(chalk.green('  => ') + chalk.white(JSON.stringify(res)));
          } else {
            warn('ThyScript compiler not available — showing raw input.');
            log(chalk.gray(`  > ${code}`));
          }
        } catch (err) {
          log(chalk.red(`  ✖ ${err.message}`));
          if (err.line) log(chalk.gray(`    at line ${err.line}`));
        }
      }
      rl.prompt();
    });

    rl.on('close', () => { log(''); process.exit(0); });
  });

// ╔══════════════════════════════════════╗
// ║  thy test                            ║
// ╚══════════════════════════════════════╝
program
  .command('test [pattern]')
  .description('Run ThyScript test files (*.test.thy)')
  .option('--watch', 'Watch for changes and re-run')
  .action(async (pattern, opts) => {
    miniBanner();
    header('TEST RUNNER');

    const cwd     = process.cwd();
    const glob    = pattern || '**/*.test.thy';
    const ThyMod  = tryRequire('src/index.js');

    // Find test files
    let testFiles = [];
    function findTests(dir) {
      const entries = fs.readdirSync(dir, { withFileTypes: true });
      for (const e of entries) {
        if (e.name === 'node_modules') continue;
        const full = path.join(dir, e.name);
        if (e.isDirectory()) findTests(full);
        else if (e.name.endsWith('.test.thy')) testFiles.push(full);
      }
    }
    try { findTests(cwd); } catch {}

    if (!testFiles.length) {
      warn('No test files found (*.test.thy)');
      process.exit(0);
    }

    info(`Found ${testFiles.length} test file(s)`);
    log('');

    async function runTests() {
      let passed = 0, failed = 0, skipped = 0;
      const startAll = Date.now();

      for (const file of testFiles) {
        const display = path.relative(cwd, file);
        const source  = fs.readFileSync(file, 'utf8');
        const t0      = Date.now();

        try {
          if (ThyMod && typeof ThyMod.run === 'function') {
            await ThyMod.run(file);
            const ms = Date.now() - t0;
            log(chalk.green(`  ✔  ${display}`) + chalk.gray(` (${ms}ms)`));
            passed++;
          } else {
            log(chalk.yellow(`  ○  ${display} (skipped — runtime unavailable)`));
            skipped++;
          }
        } catch (err) {
          const ms = Date.now() - t0;
          log(chalk.red(`  ✖  ${display}`) + chalk.gray(` (${ms}ms)`));
          log(chalk.red(`       ${err.message}`));
          failed++;
        }
      }

      const totalMs = Date.now() - startAll;
      log('');
      sep();
      log(chalk.bold.white(`  Results: `) +
          chalk.green(`${passed} passed`) + chalk.gray('  ') +
          chalk.red(`${failed} failed`) + chalk.gray('  ') +
          chalk.yellow(`${skipped} skipped`) +
          chalk.gray(`  •  ${totalMs}ms`));
      sep();
      log('');
      if (failed) process.exit(1);
    }

    await runTests();

    if (opts.watch) {
      let chokidar;
      try { chokidar = require('chokidar'); } catch {
        warn('chokidar not installed — watch mode unavailable. Run: thy use chokidar');
        process.exit(1);
      }
      log(chalk.cyan('  👁  Watching for changes...'));
      chokidar.watch('**/*.test.thy', { cwd, ignoreInitial: true })
        .on('change', async (f) => {
          log('');
          info(`Changed: ${f}. Re-running tests...`);
          testFiles = [];
          findTests(cwd);
          await runTests();
        });
    }
  });

// ╔══════════════════════════════════════╗
// ║  thy build <filename>                ║
// ╚══════════════════════════════════════╝
program
  .command('build <filename>')
  .description('Production build: compile, minify, and optimise')
  .option('-o, --out <dir>', 'Output directory', 'dist')
  .option('--no-minify', 'Skip minification')
  .action(async (filename, opts) => {
    miniBanner();
    header('PRODUCTION BUILD');

    const abs     = ensureThyFile(filename);
    const outDir  = path.resolve(process.cwd(), opts.out);
    const outFile = path.join(outDir, path.basename(abs) + '.js');
    const source  = fs.readFileSync(abs, 'utf8');
    const ThyMod  = tryRequire('src/index.js');

    fs.mkdirSync(outDir, { recursive: true });

    const s1 = ora('Compiling...').start();
    let js;
    try {
      js = ThyMod && typeof ThyMod.compile === 'function'
        ? ThyMod.compile(source, abs)
        : `// Stub build: ${path.basename(abs)}\n${source}`;
      s1.succeed('Compiled');
    } catch (err) {
      s1.fail(`Compile failed: ${err.message}`);
      process.exit(1);
    }

    if (opts.minify !== false) {
      const s2 = ora('Minifying...').start();
      try {
        const terser = require('terser');
        const res    = await terser.minify(js, { compress: true, mangle: true });
        js           = res.code || js;
        s2.succeed(`Minified (${(js.length / 1024).toFixed(1)} KB)`);
      } catch {
        try {
          const ug  = require('uglify-js');
          const res = ug.minify(js);
          if (!res.error) js = res.code;
          s2.succeed(`Minified (${(js.length / 1024).toFixed(1)} KB)`);
        } catch {
          s2.info('Minification skipped — terser/uglify-js not available');
        }
      }
    }

    const s3 = ora('Writing output...').start();
    fs.writeFileSync(outFile, js, 'utf8');
    s3.succeed(chalk.green(`Output: ${outFile}`));

    // Write build manifest
    const manifest = {
      entry: abs, outFile, size: fs.statSync(outFile).size,
      builtAt: new Date().toISOString(), version: VERSION,
    };
    fs.writeFileSync(path.join(outDir, 'thy-build.json'),
      JSON.stringify(manifest, null, 2), 'utf8');

    ok('Production build complete!');
    log('');
  });

