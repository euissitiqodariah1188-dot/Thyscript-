  _emit(line) {
    this._bodyLines.push(this._tab() + line);
  }

  _emitRaw(line) {
    this._bodyLines.push(line);
  }

  _push() { this._indent++; }
  _pop() { if (this._indent > 0) this._indent--; }

  _needRequire(pkg) { this._requires.add(pkg); }

